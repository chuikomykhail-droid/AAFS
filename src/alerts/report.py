# Reference palette of the dataviz method: first three categorical slots (validated all-pairs)
SURFACE, INK, INK_2, GRID, BAND = '#fcfcfb', '#0b0b0b', '#52514e', '#e4e3df', '#d9d8d3'
SERIES = ['#2a78d6', '#eb6834', '#1baf7a']


def write_all(art, cfg) -> list[str]:
    """Write summaries and figures; return the reference values that do not match."""
    out = path(cfg, 'reports')
    (out / 'figures').mkdir(parents=True, exist_ok=True)
    actual = reference_numbers(art, cfg)
    mismatches = [k for k, v in REFERENCE.items() if actual[k] != v]
    (out / 'stage1_summary.md').write_text(_stage1_md(actual, mismatches, art.mask_stats), encoding='utf-8')
    (out / 'stage2_summary.md').write_text(_stage2_md(art, cfg), encoding='utf-8')
    _figures(art, cfg, out / 'figures')
    for k in mismatches:
        logger.error(f'Reference mismatch: {k}: expected {REFERENCE[k]}, got {actual[k]}')
    return mismatches


# --- numbers -------------------------------------------------------------------------------
def reference_numbers(art, cfg) -> dict:
    work_start, test_start = ts(cfg['periods']['work_start']), ts(cfg['periods']['val_end'])
    df = art.df
    rec = art.scope_all[(art.scope_all['role'] == ROLE_TARGET) & (art.scope_all['started_at'] >= work_start)]
    per_loc = rec.groupby(LOC_KEY).size()
    dur_min = rec['duration'] / 60
    long_ = rec['duration'] > cfg['thresholds']['long_alert_hours'] * 3600
    fake = rec['duration'] == cfg['processor']['fake_end_duration_s']
    in_test = rec['started_at'] >= test_start

    srt = rec.sort_values(LOC_KEY + ['started_at'])
    prev_end = srt.groupby(LOC_KEY)['finished_at'].shift(1)
    rc = df.attrs['row_counts']
    tgt_units = art.units[art.units['role'] == ROLE_TARGET]
    fmt = lambda t: t.strftime('%Y-%m-%d %H:%M:%S')
    return {
        'rows raw / dedup / cleaned': f"{rc['raw']} / {rc['dedup']} / {rc['cleaned']}",
        'last start / last end in the file (UTC)': f"{fmt(df['started_at'].max())} / {fmt(df['finished_at'].max())}",
        'scope records, start >= work_start': str(len(rec)),
        'alerts per location: min / p10 / median / p90 / max':
            ' / '.join(f'{v:.0f}' for v in [per_loc.min(), per_loc.quantile(.1), per_loc.median(),
                                             per_loc.quantile(.9), per_loc.max()]),
        'duration, min: median / p75 / p99':
            ' / '.join(f'{v:.0f}' for v in [dur_min.median(), dur_min.quantile(.75), dur_min.quantile(.99)]),
        'alerts > 24 h / > 72 h / > 24 h in test':
            f"{long_.sum()} / {(rec['duration'] > 72 * 3600).sum()} / {(long_ & in_test).sum()}",
        'records of exactly 3600 s / in test': f'{fake.sum()} / {(fake & in_test).sum()}',
        'overlaps within a location': str(int((srt['started_at'] < prev_end).sum())),
        'locations / units': f"{len(tgt_units)} / {tgt_units['unit_id'].nunique()}",
        'channel outages (D15)': '; '.join(f'{fmt(o.start)} -> {fmt(o.end)}' for o in art.outages.itertuples()),
    }


def _parts(cfg) -> dict:
    p = cfg['periods']
    return {'train': (ts(p['work_start']), ts(p['train_end'])), 'val': (ts(p['train_end']), ts(p['val_end'])),
            'test': (ts(p['val_end']), ts(cfg['data_end']))}


def _stage1_md(actual: dict, mismatches: list, stats: dict) -> str:
    lines = ['# Stage 1 summary', '',
             'Generated by `scripts/run_all.py`. Reference values: DECISIONS.md, "Справочные цифры".', '',
             '| Quantity | Value | Reference | |', '|---|---|---|---|']
    for k, v in REFERENCE.items():
        lines.append(f"| {k} | {actual[k]} | {v} | {'MISMATCH' if k in mismatches else 'ok'} |")
    lines += ['', '## Mask (D10, D15)', '',
              'Counts of masked source records and of merged unit-level intervals (target units, '
              'records overlapping the working period).', '',
              '| Rule | Locations | Locations in test | Units | Units in test |', '|---|---|---|---|---|']
    for r in [LONG, FAKE_END]:
        s = stats[r]
        lines.append(f"| {r} | {s['locations']} | {s['locations_test']} | {s['units']} | {s['units_test']} |")
    lines += ['', 'Masked share of target unit-hours, %:', '', '| Reason | Train | Val | Test |', '|---|---|---|---|']
    for r, s in stats['masked_pct'].items():
        lines.append(f"| {r} | {s['train']:.2f} | {s['val']:.2f} | {s['test']:.2f} |")
    return '\n'.join(lines) + '\n'


def _stage2_md(art, cfg) -> str:
    units = art.units
    tgt = units.loc[units['role'] == ROLE_TARGET, 'unit_id'].drop_duplicates()
    iv = art.intervals
    ep = episodes(iv)
    iv_t, ep_t = iv[iv['unit_id'].isin(tgt)], ep[ep['unit_id'].isin(tgt)]
    hours = lambda d: (d['end_utc'] - d['start_utc']).dt.total_seconds().sum() / 3600
    rec = art.scope['role'].value_counts()

    lines = ['# Stage 2 summary', '', 'Generated by `scripts/run_all.py`.', '',
             '## Records to intervals', '',
             f"- Source records overlapping the working period: {len(art.scope):,} "
             f"(target {rec.get(ROLE_TARGET, 0):,}, input {rec.get(ROLE_INPUT, 0):,})",
             f"- Records outside the period, all time: {len(art.scope_all) - len(art.scope):,} (not used)",
             f'- Segments (union of overlapping records): {len(iv):,}; '
             f'records absorbed by the union: {len(art.scope) - len(iv):,}',
             f"- Episodes (pauses <= {cfg['thresholds']['pause_merge_min']} min bridged): {len(ep):,}; "
             f'pauses bridged: {len(iv) - len(ep):,}',
             f'- Target units: hours under alert {hours(iv_t):,.0f} by segments, {hours(ep_t):,.0f} by episodes '
             f'(+{hours(ep_t) - hours(iv_t):,.0f} h of bridged pauses)', '',
             '## Uncertain episodes (target units, by start)', '', '| Part | Episodes | Uncertain |', '|---|---|---|']
    for part, (lo, hi) in _parts(cfg).items():
        sel = ep_t[(ep_t['start_utc'] >= lo) & (ep_t['start_utc'] < hi)]
        lines.append(f"| {part} | {len(sel):,} | {int(sel['uncertain'].sum())} |")

    # D12, D16: where reading the tables naively as of t would differ from what was seen in real time
    T = pd.date_range(ts(cfg['periods']['warmup_end']), ts(cfg['data_end']), freq='h', inclusive='left')
    recorded = np.column_stack([_active(iv_t[iv_t['unit_id'] == u], T) for u in tgt])
    ep_active = np.column_stack([_active(ep_t[ep_t['unit_id'] == u], T) for u in tgt])
    seen = AlertHistory(iv, tgt).active(T)
    bridged = ep_active & ~recorded
    held_open = seen & ~recorded
    lines += ['', '## As-of state on the hourly grid (D12, D16)', '',
              f'- Hourly moments from warmup_end to data_end: {len(T):,}',
              f'- Bridged pauses: episode says "alert", recorded segments say "quiet": {bridged.sum():,} '
              f'unit-moments, {bridged.any(axis=1).sum():,} moments ({bridged.any(axis=1).mean():.1%})',
              f'- Invented ends: recorded segments say "quiet", but no all-clear had been seen, so '
              f'AlertHistory keeps the alert open: {held_open.sum():,} unit-moments, '
              f'{held_open.any(axis=1).sum():,} moments ({held_open.any(axis=1).mean():.1%})',
              '- Features read the state only through AlertHistory']
    lines += ['', '## Outages (D15)', '']
    lines += [f'- {o.start} -> {o.end} ({o.end - o.start})' for o in art.outages.itertuples()] or ['- none']
    return '\n'.join(lines) + '\n'


def _active(ep: pd.DataFrame, T) -> np.ndarray:
    s, e, t = to_sec(ep['start_utc']), to_sec(ep['end_utc']), to_sec(T)
    k = np.searchsorted(s, t, side='right') - 1
    return (k >= 0) & (e[np.maximum(k, 0)] > t) if len(s) else np.zeros(len(t), dtype=bool)


# --- figures -------------------------------------------------------------------------------
def _style(ax, grid_axis='y'):
    ax.set_facecolor(SURFACE)
    for side in ['top', 'right']:
        ax.spines[side].set_visible(False)
    for side in ['left', 'bottom']:
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=INK_2, labelsize=9, length=0)
    ax.grid(axis=grid_axis, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def _title(fig, title, subtitle):
    fig.text(0.01, 0.985, title, ha='left', va='top', fontsize=13, color=INK, weight='bold')
    fig.text(0.01, 0.94, subtitle, ha='left', va='top', fontsize=9.5, color=INK_2)


def _save(fig, file):
    fig.savefig(file, dpi=150, facecolor=SURFACE)
    plt.close(fig)


def _figures(art, cfg, out):
    work_start, data_end = ts(cfg['periods']['work_start']), ts(cfg['data_end'])
    _fig_levels(art.df, work_start, out / 'level_transition.png')
    _fig_units(art, cfg, out / 'alerts_per_unit.png')
    _fig_durations(art, cfg, out / 'durations.png')
    _fig_jaccard(art.pairs, cfg['thresholds']['clone_jaccard'], cfg['thresholds']['similar_pairs_report'],
                 out / 'jaccard.png')
    _fig_outage(art, cfg, out / 'outage.png')


def _fig_levels(df, work_start, file):
    d = df[df['started_at'] >= pd.Timestamp('2024-01-01', tz='UTC')]
    month = d['started_at'].dt.tz_localize(None).dt.to_period('M')
    share = pd.crosstab(month, d['level'], normalize='index')[['raion', 'oblast', 'hromada']]
    x = share.index.to_timestamp()
    fig, ax = plt.subplots(figsize=(10, 4.8))
    fig.subplots_adjust(top=0.82, left=0.07, right=0.88, bottom=0.1)
    for col, color in zip(share.columns, SERIES):
        ax.plot(x, share[col], color=color, linewidth=2, label=col)
        ax.text(x[-1] + pd.Timedelta(days=12), share[col].iloc[-1], col, color=INK, fontsize=9, va='center')
    ws = work_start.tz_localize(None)
    ax.axvline(ws, color=INK_2, linewidth=1, linestyle='--')
    ax.text(ws, 1.02, ' work_start 2025-11-07', color=INK_2, fontsize=8.5, va='bottom')
    ax.set_ylim(0, 1)
    ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1.0))
    ax.legend(frameon=False, fontsize=9, loc='center left', labelcolor=INK)
    _style(ax)
    _title(fig, 'Raion records replace oblast records by November 2025',
           'Share of records by level per month (all oblasts), 2024-01 to 2026-09')
    _save(fig, file)


def _fig_units(art, cfg, file):
    units = art.units[art.units['role'] == ROLE_TARGET]
    ep = episodes(art.intervals)
    ep = ep[(ep['start_utc'] >= ts(cfg['periods']['work_start'])) & (ep['start_utc'] < ts(cfg['data_end']))]
    per_unit = ep.groupby('unit_id').size()
    u = units.drop_duplicates('unit_id').assign(n=lambda x: x['unit_id'].map(per_unit).fillna(0))
    order = u.groupby('oblast')['n'].median().sort_values().index
    y = {ob: i for i, ob in enumerate(order)}
    fig, ax = plt.subplots(figsize=(10, 7.5))
    fig.subplots_adjust(top=0.9, left=0.2, right=0.97, bottom=0.07)
    ax.scatter(u['n'], u['oblast'].map(y), s=36, color=SERIES[0], edgecolors=SURFACE, linewidths=1, zorder=3)
    ax.set_yticks(range(len(order)), [ob.replace(' oblast', '') for ob in order])
    ax.set_xlabel('alert episodes per unit', color=INK_2, fontsize=9)
    _style(ax, grid_axis='x')
    med = u.groupby('oblast')['n'].median()
    spread = u.groupby('oblast')['n'].agg(lambda n: n.max() / n.min())
    _title(fig, f'Alert frequency varies {med.max() / med.min():.0f}x across oblasts '
                f'and up to {spread.max():.1f}x within one',
           f'Episodes per unit, {cfg["periods"]["work_start"][:10]} to {cfg["data_end"][:10]}; '
           f'one dot per unit ({len(u)} units), oblasts sorted by median')
    _save(fig, file)


def _fig_durations(art, cfg, file):
    rec = art.scope_all[(art.scope_all['role'] == ROLE_TARGET)
                        & (art.scope_all['started_at'] >= ts(cfg['periods']['work_start']))]
    hours = rec['duration'] / 3600
    long_h = cfg['thresholds']['long_alert_hours']
    bins = np.logspace(np.log10(hours.min()), np.log10(hours.max()), 60)
    fig, ax = plt.subplots(figsize=(10, 4.8))
    fig.subplots_adjust(top=0.82, left=0.08, right=0.97, bottom=0.12)
    ax.hist(hours, bins=bins, color=SERIES[0], edgecolor=SURFACE, linewidth=0.6)
    ax.set_xscale('log')
    ax.set_yscale('log')
    ax.axvline(long_h, color=INK_2, linewidth=1, linestyle='--')
    n_long = int((hours > long_h).sum())
    ax.text(long_h * 1.08, ax.get_ylim()[1] * 0.5, f'{long_h} h: {n_long} longer alerts\nmasked, rule (a)',
            color=INK_2, fontsize=8.5, va='top')
    ax.xaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(
        lambda v, _: f'{v * 3600:.0f} s' if v < 1 / 60 else f'{v * 60:.0f} min' if v < 1 else f'{v:.0f} h'))
    ax.set_xlabel('duration (log scale)', color=INK_2, fontsize=9)
    ax.set_ylabel('records (log scale)', color=INK_2, fontsize=9)
    _style(ax)
    _title(fig, 'Past 24 hours only a thin tail and a 100-hour spike of lost all-clears remain',
           f'Durations of {len(rec):,} target records since work_start; median '
           f'{hours.median() * 60:.0f} min, p99 {hours.quantile(.99):.1f} h')
    _save(fig, file)


def _fig_jaccard(pairs, threshold, report_from, file):
    fig, (a, b) = plt.subplots(1, 2, figsize=(10, 4.5), gridspec_kw={'width_ratios': [3, 2]})
    fig.subplots_adjust(top=0.8, left=0.07, right=0.97, bottom=0.13, wspace=0.18)
    a.hist(pairs['jaccard'], bins=np.linspace(0, 1, 51), color=SERIES[0], edgecolor=SURFACE, linewidth=0.6)
    a.set_xlabel('Jaccard similarity, all same-oblast pairs', color=INK_2, fontsize=9)
    a.set_ylabel('pairs', color=INK_2, fontsize=9)
    top = pairs[pairs['jaccard'] >= report_from]
    b.hist(top['jaccard'], bins=np.linspace(report_from, 1, 51), color=SERIES[0], edgecolor=SURFACE, linewidth=0.6)
    b.axvline(threshold, color=INK_2, linewidth=1, linestyle='--')
    b.text(threshold - 0.0005, b.get_ylim()[1] * 0.95, f'merge >= {threshold}', color=INK_2,
           fontsize=8.5, ha='right', va='top')
    b.set_xlabel(f'zoom: pairs >= {report_from}', color=INK_2, fontsize=9)
    for ax in (a, b):
        _style(ax)
    n_merge = int((pairs['jaccard'] >= threshold).sum())
    _title(fig, 'Similarity of raion series is a continuum; the clone threshold is fixed in advance',
           f'{len(pairs)} same-oblast pairs, train period; {len(top)} pairs >= {report_from}, '
           f'{n_merge} pairs >= {threshold} form the clone groups (D07)')
    _save(fig, file)


def _fig_outage(art, cfg, file):
    """Validation and test windows, one bar per day; the outage band is drawn behind the bars."""
    work_start, data_end = ts(cfg['periods']['work_start']), ts(cfg['data_end'])
    val_start, test_start = ts(cfg['periods']['train_end']), ts(cfg['periods']['val_end'])
    df = art.df[(art.df['started_at'] >= work_start) & (art.df['started_at'] < data_end)]
    day = df['started_at'].dt.tz_localize(None).dt.floor('D')
    days = pd.date_range(work_start.tz_localize(None), data_end.tz_localize(None), freq='D', inclusive='left')
    per_day = day.value_counts().reindex(days, fill_value=0)
    shown = per_day[per_day.index >= val_start.tz_localize(None)]
    top = shown.max() * 1.25

    fig, ax = plt.subplots(figsize=(10, 4.5))
    fig.subplots_adjust(top=0.8, left=0.07, right=0.97, bottom=0.1)
    for o in art.outages.itertuples():
        s, e = o.start.tz_localize(None), o.end.tz_localize(None)
        ax.axvspan(s, e, color=BAND, linewidth=0, zorder=0)
        ax.text(s + (e - s) / 2, top * 0.97, f'channel silent\n{(o.end - o.start).total_seconds() / 86400:.1f} days',
                color=INK, fontsize=8.5, ha='center', va='top')
    ax.bar(shown.index + pd.Timedelta(hours=12), shown.to_numpy(), width=0.8, color=SERIES[0], zorder=2)
    for x, label in [(val_start, 'validation'), (test_start, 'test')]:
        x = x.tz_localize(None)
        ax.axvline(x, color=INK_2, linewidth=1, linestyle='--')
        ax.text(x + pd.Timedelta(hours=10), top * 0.97, label, color=INK_2, fontsize=8.5, va='top')
    ax.set_ylim(0, top)
    ax.set_ylabel('alert starts per day, all levels', color=INK_2, fontsize=9)
    _style(ax)
    _title(fig, 'The channel went silent for four days inside the test window',
           f'Alert starts per day in the whole file; median {per_day.median():.0f} over the working period, '
           f'zero on {int((per_day == 0).sum())} days (D15)')
    _save(fig, file)
