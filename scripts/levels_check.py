MIN_DAYS, MIN_POS = 7, 200          # below this a part gets numbers but no conclusions (task of D23)


def ci(v, lo, hi, sign=False):
    if pd.isna(v):
        return '—'
    f = '{:+.3f}' if sign else '{:.3f}'
    return f'{f.format(v)} [{f.format(lo)}, {f.format(hi)}]'


def cell(tab, model, metric, diff=False):
    r = tab[(tab['model'] == model) & (tab['metric'] == metric)].iloc[0]
    return ci(r['diff'], r['diff_lo'], r['diff_hi'], True) if diff else ci(r['value'], r['lo'], r['hi'])


def enough(tab):
    return tab.attrs['n_days'] >= MIN_DAYS and tab.attrs['n_pos'] >= MIN_POS


def part_rows(parts: dict, model: str, ref: str) -> list:
    md = []
    for p in ['before', 'after']:
        if p not in parts:
            md.append(f'| {p} | 0 | 0 | 0 | | | | no rows |')
            continue
        t = parts[p]
        note = '' if enough(t) else f'fewer than {MIN_DAYS} days or {MIN_POS} positives: no conclusions'
        md.append(f"| {p} | {t.attrs['n_rows']:,} | {t.attrs['n_pos']:,} | {t.attrs['n_days']} | "
                  f"{cell(t, model, 'pr_auc')} | {cell(t, ref, 'pr_auc')} | {cell(t, model, 'pr_auc', True)} | "
                  f"{cell(t, model, 'log_loss', True)} | {note} |")
    return md


def examples(raw_dir) -> list:
    """Records of the response files exactly as saved (response bodies only; the token is never in them)."""
    picks = [('yellow', 'raion'), ('red', 'raion'), ('yellow', 'oblast'), ('red', 'oblast'), ('yellow', 'hromada'), ('red', 'city')]
    found, noted = {}, []
    for f in sorted(Path(raw_dir).glob('*_*.json')):
        for a in json.loads(f.read_text(encoding='utf-8'))['alerts']:
            key = (a.get('alert_level'), a.get('location_type'))
            if a.get('alert_type') == 'air_raid' and a['started_at'] >= '2026-10-01' and key in picks and key not in found:
                found[key] = a
            if 'жовт' in (a.get('notes') or ''):
                noted.append(a)
    return [json.dumps(found[k], ensure_ascii=False) for k in picks if k in found] + [json.dumps(a, ensure_ascii=False) for a in noted]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--preds-cache', help='parquet file to keep the frozen stage 8 predictions between runs')
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO, format='%(levelname)s: %(name)s: %(message)s')
    t0 = time.time()
    cfg = load_config()
    L = cfg['levels']
    h = L['horizon']
    out = path(cfg, 'reports')
    md = ['# Two alert levels, yellow and red (D23)', '',
          'Generated by `scripts/levels_check.py`. Decisions: DECISIONS.md, D23. Models, hyperparameters, features and '
          'the target are unchanged (rule 6): the target is still "an alert of any level starts in (t, t+h]". '
          'The token is not read here; the examples below come from the saved response bodies, which never contain it.', '']

    raw_dir = ROOT / cfg['api']['raw_dir']
