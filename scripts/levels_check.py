            share = '' if pd.isna(r['share_of_positives']) else f"{r['share_of_positives']:.1%}"
            md.append(f"| {r['group']} | {r['rows']:,} | {share} | {r['mean_p_LGBM']:.3f} | {r[f'mean_p_{ref}']:.3f} {auc}")
