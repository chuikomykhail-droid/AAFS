    overall_live = bootstrap(live_rows, ['B1_live', 'LGBM'], bs['n_reps'], bs['seed'], bs['ci'], 'B1_live')
    rl = lv.record_levels(recs, raw, units)
    level = lv.first_level(preds, rl, h)
    mismatch = int((level.notna() != (preds['y'] == 1)).sum())
