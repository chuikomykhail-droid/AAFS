    lviv = kept[kept['location_oblast'] == 'Львівська область']
    lviv_red = lviv[lviv['alert_level'] == 'red'].groupby(lviv['started_at'].dt.floor('h'))['location_title'].nunique()
    lviv_y = lviv[lviv['alert_level'] == 'yellow'].groupby(lviv['started_at'].dt.floor('h'))['location_title'].nunique()
    md += ['', f"Lviv oblast (7 raions): red alerts come as waves over {lviv_red.min()}-{lviv_red.max()} raions within "
           f"seconds ({len(lviv_red)} waves; hours with a red start); yellow ones cover {lviv_y.min()}-{lviv_y.max()} raions ({len(lviv_y)} hours with a yellow start). "
           'The first yellow record of the oblast is on 2026-09-12, a month before the date in the source.', '']

    # --- step 3: the main test without Kyiv after the start of the system ----------------
    grid = pd.read_parquet(path(cfg, 'grid'))
    kyiv_start, stop = ts(L['kyiv_start']), ts(L['channel_stop'])
