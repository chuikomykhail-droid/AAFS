    md += examples(raw_dir) + ['```', '']

    # --- step 2: transition by oblast ------------------------------------------------------
    recent = raw[raw['started_at'] >= window_start - pd.Timedelta(days=7)]   # drops the alerts open since 2022-2024
    tr = lv.transitions(recent)
