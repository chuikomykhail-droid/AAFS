    by_en = tr.set_index('oblast')['first_yellow']
    dates_data = {ob: by_en.get(ob, pd.NaT) for ob in target_oblasts}
    dates_src = {ob: d for ob, (d, _) in sources.items()}
    md += ['Before / after the transition of the row\'s oblast (by the forecast moment t). LightGBM - reference: paired '
           f'bootstrap over days. A part with fewer than {MIN_DAYS} days or {MIN_POS} positives is shown without conclusions.', '']
    for label, dates in [('Transition dates from the data (first yellow record; no yellow = "before")', dates_data),
                         ('Transition dates from the sources (Kyiv City 6.09, Lviv oblast 12.10; other oblasts left out)', dates_src)]:
        part = lv.split_parts(preds, dates)
        for ref, sub in [('B1', preds), ('B1_live', live_rows)]:
            names = [ref, 'LGBM']
            parts = lv.part_metrics(sub, part.loc[sub.index], names, cfg, ref)
            md += [f'{label}; reference {ref}:', '',
                   f'| Part | Rows | Positives | Days | LightGBM, PR-AUC | {ref}, PR-AUC | LightGBM - {ref}, PR-AUC | '
                   f'LightGBM - {ref}, log loss | Note |', '|---|---|---|---|---|---|---|---|---|']
            md += part_rows(parts, 'LGBM', ref)
            md.append('')
            ob_before = sorted(set(sub.loc[part.loc[sub.index] == 'before', 'oblast']))
            md += [f"Oblasts in 'before': {', '.join(ob_before) or 'none'}.", '']

    # --- step 5: regimes without models ---------------------------------------------------
    hi_v = art_v.outages['start'].min().floor('D')
    lo_v = hi_v - pd.Timedelta(days=28)
    lo_a, hi_a = ts(cfg_a['periods']['work_start']), ts(cfg_a['data_end'])
